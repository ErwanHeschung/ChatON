"""Generates src/app/shared/components/network/world.ts: the network map in the Equal Earth
projection (land, graticule, outline, as SVG paths) and a point per country (ISO 3166
alpha-2), for NIP-11 `relay_countries`. `projection.ts` projects the same way at run time.

Data: Natural Earth (public domain) through the npm packages world-atlas@2.0.2 and
i18n-iso-countries@7.11.0 (codes only), unpacked with `npm pack` into DIR.
Usage: python3 -I scripts/world.py DIR > src/app/shared/components/network/world.ts
"""
import json
import math
import sys

DIR = sys.argv[1]
WIDTH = 1000

# Equal Earth (Šavrič, Patterson, Jenny 2018). Keep in step with projection.ts.
A1, A2, A3, A4 = 1.340264, -0.081106, 0.000893, 0.003796
M = math.sqrt(3) / 2


def equal_earth(lon, lat):
    t = math.asin(M * math.sin(math.radians(lat)))
    t2, t6 = t * t, t ** 6
    x = 2 * math.sqrt(3) * math.radians(lon) * math.cos(t) / (3 * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)))
    y = t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))
    return x, y


XMAX, YMAX = equal_earth(180, 0)[0], equal_earth(0, 90)[1]
R = WIDTH / (2 * XMAX)


def svg(lon, lat):
    x, y = equal_earth(lon, lat)
    return R * (x + XMAX), R * (YMAX - y)


def num(v):
    """One decimal, no trailing `.0`, no `-0`."""
    n = f"{v:.1f}".removesuffix(".0")
    return "0" if n == "-0" else n


def split(ring):
    """A ring that jumps from 180° to -180° (Fiji) would draw a line across the world:
    cut it there, each piece on its own side."""
    pieces = [[ring[0]]]
    for a, b in zip(ring, ring[1:]):
        if abs(b[0] - a[0]) > 180:
            pieces.append([])
        pieces[-1].append(b)
    return pieces


def path(rings, closed=True, cut=False):
    """Relative commands, one decimal, points closer than half a unit dropped."""
    out = []
    for ring in (piece for whole in rings for piece in (split(whole) if cut else [whole])):
        pts = [svg(*p) for p in ring]
        kept = [pts[0]]
        for p in pts[1:]:
            if math.dist(p, kept[-1]) >= 0.5:
                kept.append(p)
        if closed and len(kept) < 3:
            continue
        cmd, (px, py) = [f"M{kept[0][0]:.1f} {kept[0][1]:.1f}"], (round(kept[0][0], 1), round(kept[0][1], 1))
        for x, y in kept[1:]:
            x, y = round(x, 1), round(y, 1)
            cmd.append(f"{num(x - px)} {num(y - py)}")
            px, py = x, y
        out.append(cmd[0] + "l" + " ".join(cmd[1:]) + ("z" if closed else ""))
    return "".join(out)


def decode(topo, name):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x, y = x + dx, y + dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)

    def ring(ids):
        pts = []
        for i in ids:
            a = arcs[i] if i >= 0 else arcs[~i][::-1]
            pts.extend(a if not pts else a[1:])
        return pts

    for geo in topo["objects"][name]["geometries"]:
        polys = geo["arcs"] if geo["type"] == "MultiPolygon" else [geo["arcs"]] if geo["type"] == "Polygon" else []
        yield geo.get("id"), [[ring(r) for r in poly] for poly in polys]


def area_centroid(ring):
    # Unwrap longitudes across the antimeridian (Russia, Fiji), or the area is garbage.
    unwrapped = [ring[0]]
    for x, y in ring[1:]:
        px = unwrapped[-1][0]
        x += 360 * round((px - x) / 360)
        unwrapped.append((x, y))
    ring = unwrapped
    a = cx = cy = 0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        c = x1 * y2 - x2 * y1
        a, cx, cy = a + c, cx + (x1 + x2) * c, cy + (y1 + y2) * c
    return abs(a / 2), (cx / (3 * a), cy / (3 * a)) if a else ring[0]


land = [r for _, polys in decode(json.load(open(f"{DIR}/world-atlas-2.0.2/package/land-110m.json")), "land") for p in polys for r in p]
lats = range(-90, 91, 2)
graticule = [[(lon, lat) for lat in lats] for lon in range(-150, 180, 30)]
graticule += [[(lon, lat) for lon in range(-180, 181, 5)] for lat in range(-60, 90, 30)]
outline = [[(-180, lat) for lat in lats] + [(180, lat) for lat in reversed(lats)]]

alpha2 = {int(c[2]): c[0] for c in json.load(open(f"{DIR}/i18n-iso-countries-7.11.0/package/codes.json"))}
points, areas = {}, {}
for cid, polys in decode(json.load(open(f"{DIR}/world-atlas-2.0.2/package/countries-50m.json")), "countries"):
    if cid is None or int(cid) not in alpha2 or not polys:
        continue
    area, (x, y) = max(area_centroid(p[0]) for p in polys)
    code = alpha2[int(cid)]
    # Several features can share a code (Australia and Ashmore Reef): the biggest land wins.
    if area > areas.get(code, 0):
        areas[code] = area
        points[code] = [round((x + 180) % 360 - 180, 1), round(y, 1)]

print("// Generated by scripts/world.py from Natural Earth (public domain). Don't edit.")
print("/** Equal Earth scale: SVG units per radian-ish unit, so the world is 1000 wide. */")
print(f"export const R = {R:.4f};")
print("/** The whole world, its outline the frame: `viewBox`. */")
print(f"export const VIEW = [0, 0, {WIDTH}, {2 * R * YMAX:.1f}] as const;")
print(f"export const LAND = {json.dumps(path(land, cut=True))};")
print(f"/** Every 30°. */")
print(f"export const GRID = {json.dumps(path(graticule, closed=False))};")
print(f"/** The edge of the world. */")
print(f"export const OUTLINE = {json.dumps(path(outline))};")
print("/** [longitude, latitude] of each country (ISO 3166 alpha-2), on its largest piece of land. */")
print("export const COUNTRIES: Record<string, [number, number]> = " + json.dumps(points, separators=(",", ":"), sort_keys=True) + ";")
